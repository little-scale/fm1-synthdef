#!/usr/bin/env python3
"""Reproducible float-only C adaptation of pinned SC 3.14.1 ChaosUGens."""
from pathlib import Path
import re,json,hashlib
r=Path(__file__).resolve().parents[1];p=r/'reference/ChaosUGens.cpp';src=p.read_text()
assert hashlib.sha256(p.read_bytes()).hexdigest()==json.loads((r/'reference/sources.json').read_text())['sha256']['ChaosUGens.cpp']
names=['HenonN','HenonL','HenonC','CuspN','CuspL','LatoocarfianN','LatoocarfianL','LatoocarfianC','LorenzL','FBSineN','FBSineL','FBSineC','StandardN','StandardL']
fields='x0 y0 z0 x1 xn yn zn xnm1 ynm1 znm1 xnm2 xnm3 frac c0 c1 c2 c3 a b counter stable'.split()
out=['''/* Generated by tools/generate-chaos.py from SC 3.14.1 ChaosUGens.cpp.
 * Copyright 2002 James McCartney; Chaos UGens by Lance Putnam (2004). GPL-3.0-or-later adaptation; original
 * GPL-2.0-or-later notice retained in reference/ChaosUGens.cpp.
 * Deliberately single precision. Equations, interpolation and resets retained. */
typedef struct {float x0,y0,z0,x1,xn,yn,zn,xnm1,ynm1,znm1,xnm2,xnm3,frac,c0,c1,c2,c3,a,b,counter;int stable;} chaos_state;
typedef char chaos_fits_node[(sizeof(chaos_state)<=offsetof(fm_state,initialized))?1:-1];
typedef struct {chaos_state *s;const float *args;float *out;float sr;} chaos_unit;
#define CHAOS_COEF(X3,X2,X1,X,C0,C1,C2,C3) do { C0=X2; C1=.5f*(X1-X3); C2=X3-2.5f*X2+X1+X1-.5f*X; C3=.5f*(X-X3)+1.5f*(X2-X1); } while(0)
static float chaos_mod2pi(float x){return bounded_wrap(x,0,TAU);}
static float chaos_ipol(float f,float c0,float c1,float c2,float c3){return ((c3*f+c2)*f+c1)*f+c0;}
''']
for name in names:
 for suffix in ['next','Ctor']:
  m=re.search(r'void '+name+'_'+suffix+r'\([^)]*\) \{',src);assert m
  end=m.end();depth=1
  while depth:
   depth+=(src[end]=='{')-(src[end]=='}');end+=1
  code=src[m.start():end];code=re.sub(r'//[^\n]*','',code)
  code=code.replace('void '+name+'_', 'static void chaos_'+name+'_').replace(name+'* unit','chaos_unit* unit')
  code=re.sub(r'SETCALC\([^;]+;','',code).replace(name+'_next(unit, 1)','chaos_'+name+'_next(unit, 1)')
  code=code.replace('unit->mRate->mSampleRate','unit->sr').replace('ZOUT(0)','unit->out').replace('ZXP(out)','*out++')
  code=re.sub(r'ZIN0\((\d+)\)',r'unit->args[\1]',code)
  for f in fields:code=re.sub(r'unit->'+f+r'\b','unit->s->'+f,code)
  code=re.sub(r'\bdouble\b','float',code).replace('bool ','int ').replace('true','1').replace('false','0')
  code=code.replace('sc_max','fmaxf').replace('sc_abs','fabsf').replace('sqrt(','sqrtf(').replace('sin(','sinf(')
  code=code.replace('mod2pi(', 'chaos_mod2pi(').replace('RECPI','(1.0f/PI)')
  code=code.replace('ipol3Coef','CHAOS_COEF').replace('ipol3(','chaos_ipol(').replace('ONESIXTH','(1.0f/6.0f)')
  code=re.sub(r'(?<![\w.])(\d+\.\d*|\.\d+)(?![\w.])',r'\1f',code)
  out.append(code+'\n')
out.append('#undef CHAOS_COEF\n')
(r/'src/fm_chaos.inc').write_text('\n'.join(line.rstrip() for line in '\n'.join(out).splitlines())+'\n')
