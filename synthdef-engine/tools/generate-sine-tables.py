#!/usr/bin/env python3
"""Build-time tables following SC 3.14.1 common/Samp.cpp. No runtime allocation."""
import math
from pathlib import Path
import struct
f32=lambda x:struct.unpack('<f',struct.pack('<f',x))[0]
sine=[f32(math.sin(i*(2*math.pi/8192))) for i in range(8193)]
bad=lambda i:min(abs(i),abs(i-4096),abs(i-8192))<=8
cosecant=[0.0 if bad(i) else f32(1.0/x) for i,x in enumerate(sine)]
out=['/* SPDX-License-Identifier: GPL-3.0-or-later */','/* Generated by tools/generate-sine-tables.py; SC 3.14.1 Samp.cpp definitions. */']
for name,values in [('fm_sine',sine),('fm_cosecant',cosecant)]:
    out.append(f'static const float {name}[8193] = {{')
    for i in range(0,len(values),8):out.append(' '+','.join(x.hex()+'f' for x in values[i:i+8])+',')
    out.append('};')
(Path(__file__).resolve().parents[1]/'src/fm_tables.inc').write_text('\n'.join(out)+'\n')
